const GU_DIGITS = '૦૧૨૩૪૫૬૭૮૯';

export function makeT(lang) {
  const dict = STRINGS[lang] || STRINGS.gu;
  const num = (n) => (lang === 'gu' ? String(n).replace(/\d/g, (d) => GU_DIGITS[d]) : String(n));
  const t = (key, vars = {}) =>
    (dict[key] ?? STRINGS.gu[key] ?? key).replace(/\{(\w+)\}/g, (_, k) =>
      typeof vars[k] === 'number' ? num(vars[k]) : vars[k] ?? ''
    );
  const link = (vachno) => `https://www.anirdesh.com/vachanamrut/index.php?format=${lang}&vachno=${vachno}`;
  return { lang, t, num, link };
}

export const LangContext = createContext(makeT('gu'));
export const useLang = () => useContext(LangContext);
